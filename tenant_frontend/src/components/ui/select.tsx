"use client"

import * as React from "react"
import * as SelectPrimitive from "@radix-ui/react-select"
import { CheckIcon, ChevronDownIcon, ChevronUpIcon } from "lucide-react"

import { cn } from "@/lib/utils"
import { FormSurfaceContext } from "@/components/ui/form-surface"

function Select({
  value,
  defaultValue,
  onValueChange,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Root>) {
  // Radix UI requires non-empty strings for SelectItem values.
  // Map empty strings to/from sentinel "__EMPTY__" to guarantee zero crashes across all consumers.
  const mappedValue = value === "" ? "__EMPTY__" : value
  const mappedDefaultValue = defaultValue === "" ? "__EMPTY__" : defaultValue
  const handleValueChange = onValueChange
    ? (val: string) => onValueChange(val === "__EMPTY__" ? "" : val)
    : undefined

  return (
    <SelectPrimitive.Root
      data-slot="select"
      value={mappedValue}
      defaultValue={mappedDefaultValue}
      onValueChange={handleValueChange}
      {...props}
    />
  )
}

